def metric_keys(metric: str, hive: Optional[int]) -> list[str]:
    """Measurement keys for ``metric`` on ``hive``, best candidate first.

    Device-level metrics ignore ``hive``. Hive-level metrics substitute the hive
    number into the templated keys and append the legacy flat column for hives
    1–2 where one exists (older rows carry only ``mic_left_*``/``mic_right_*``).
    """
    spec = METRICS[metric]
    if spec["scope"] == "device":
        return list(spec["keys"])
    if hive is None:
        raise ValueError(f"metric '{metric}' is per hive and needs a hive number")
    keys = [k.format(n=hive) for k in spec["keys"]]
    legacy = (spec.get("legacy") or {}).get(hive)
    if legacy:
        keys.append(legacy)
    return keys


def _numeric(value: Any) -> Optional[float]:
    """Coerce a measurement value to a float, or None if it is not a number.

    Postgres NUMERIC columns come back as Decimal, and some values arrive as
    numeric-looking strings out of raw_json; both must plot.
    """
    if value is None or isinstance(value, bool):
        return None
    try:
        out = float(value)
    except (TypeError, ValueError):
        return None
    return out if out == out and out not in (float("inf"), float("-inf")) else None


def series_points(
    measurements: list[dict], keys: list[str], aggregate: str = "none"
) -> list[list]:
    """Build ``[[iso8601, value], …]`` (oldest first) for one published series.

    ``measurements`` is the newest-first list the chart query returns. For each
    row the first non-null key wins, mirroring the dashboard's coalescing.

    ``aggregate`` buckets the points by UTC calendar day: ``daily_max`` /
    ``daily_min`` keep the extreme reading (stamped at the moment it happened,
    as the dashboard's daily-max chart does), ``daily_avg`` averages the day and
    stamps it at midday. Buckets are built from the sampled rows the query
    returned, so on multi-year ranges a daily extreme is a close approximation
    rather than an exhaustive scan.
    """
    raw: list[tuple[datetime, float]] = []
    for m in measurements:
        at = m.get("measured_at")
        if at is None:
            continue
        value = None
        for k in keys:
            if m.get(k) is not None:
                value = _numeric(m[k])
                break
        if value is None:
            continue
        raw.append((at, value))
    raw.sort(key=lambda p: p[0])

    if aggregate == "none" or not raw:
        return [[_iso(at), v] for at, v in raw]

    buckets: dict[Any, list[tuple[datetime, float]]] = {}
    for at, v in raw:
        buckets.setdefault(at.astimezone(timezone.utc).date(), []).append((at, v))

    out: list[list] = []
    for day in sorted(buckets):
        rows = buckets[day]
        if aggregate == "daily_avg":
            mean = sum(v for _, v in rows) / len(rows)
            noon = datetime(day.year, day.month, day.day, 12, tzinfo=timezone.utc)
            out.append([_iso(noon), mean])
            continue
        pick = max(rows, key=lambda p: p[1]) if aggregate == "daily_max" else min(rows, key=lambda p: p[1])
        out.append([_iso(pick[0]), pick[1]])
    return out


def _iso(at: datetime) -> str:
    """UTC ISO-8601 with a trailing Z, which every browser's Date() parses."""
    if at.tzinfo is None:
        at = at.replace(tzinfo=timezone.utc)
    return at.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")


