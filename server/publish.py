"""Publish data: public, read-only embeds of a chosen slice of hive data.

The local dashboard is login-protected end to end, which is right for a control
surface but leaves no way to show "how heavy is the hive today" on a club
website, a blog or a shop page. This module adds the missing, explicit step:

1. An admin publishes a chart from the dashboard's **Publish** view — a metric,
   an ordered list of hives, a rolling period and a few presentation options.
2. The server mints an unguessable token and serves exactly that slice, with no
   login, from two public routes:

   * ``GET /embed/chart/{token}``          — a self-contained page to ``<iframe>``
   * ``GET /api/v1/public/charts/{token}`` — the same data as JSON (CORS: ``*``),
     plus ``…/{token}.csv`` for spreadsheets

Everything else stays private. Nothing is public until someone publishes it,
the payload carries resolved display labels rather than device ids, and a
publication is revoked by deleting it (or clearing ``enabled``) — the token is
the capability, so revocation is immediate.

The management API lives under ``/api/v1/local/publish/*`` next to the rest of
the dashboard API: reading the list needs a session, creating/editing/deleting
needs the admin role. The whole feature (public routes included) is gated by
ENABLE_LOCAL_DASHBOARD and ENABLE_PUBLIC_EMBEDS.
"""

