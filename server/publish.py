CHART_COLUMNS = """
    id, token, title, subtitle, metric, chart_type, aggregate, series,
    range_days, options, enabled, created_at, updated_at, view_count, last_viewed_at
"""


def _row_to_chart(r) -> dict:
    return {
        "id": r[0],
        "token": r[1],
        "title": r[2],
        "subtitle": r[3],
        "metric": r[4],
        "chart_type": r[5],
        "aggregate": r[6],
        "series": r[7] or [],
        "range_days": r[8],
        "options": r[9] or {},
        "enabled": bool(r[10]),
        "created_at": r[11],
        "updated_at": r[12],
        "view_count": r[13],
        "last_viewed_at": r[14],
    }


def _new_token() -> str:
    return secrets.token_urlsafe(16)


def _validate_metric(metric: str) -> dict:
    spec = METRICS.get(metric)
    if spec is None:
        raise HTTPException(
            status_code=400,
            detail=f"Unknown metric '{metric}'. See GET /api/v1/local/publish/metrics.",
        )
    return spec


def _validate_series(spec: dict, series: list) -> list[dict]:
    """Check the requested series against the metric's scope and the device list.

    A hive metric needs a hive number on every series; a device metric must not
    carry one (publishing "ambient temperature of hive 3" would silently plot the
    whole collector's reading under a hive's name). Unknown devices are rejected
    here rather than becoming an embed that renders empty forever.
    """
    known = _known_device_ids([s.device_id for s in series])
    out: list[dict] = []
    seen: set[tuple[str, Optional[int]]] = set()
    for s in series:
        if s.device_id not in known:
            raise HTTPException(status_code=404, detail=f"Unknown device: {s.device_id}")
        hive = s.hive
        if spec["scope"] == "hive" and hive is None:
            raise HTTPException(
                status_code=400,
                detail="This metric is measured per hive — every series needs a hive number.",
            )
        if spec["scope"] == "device":
            hive = None
        key = (s.device_id, hive)
        if key in seen:
            raise HTTPException(
                status_code=400,
                detail=(
                    "The same device is published twice in this chart."
                    if spec["scope"] == "device"
                    else "The same hive is published twice in this chart."
                ),
            )
        seen.add(key)
        out.append({"device_id": s.device_id, "hive": hive, "label": s.label.strip()})
    return out


def _known_device_ids(candidates: list[str]) -> set[str]:
    if not candidates:
        return set()
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT device_id FROM devices WHERE device_id = ANY(%s);",
                (list(set(candidates)),),
            )
            return {row[0] for row in cur.fetchall()}


def _fetch_chart_by_id(chart_id: int) -> Optional[dict]:
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.execute(
                f"SELECT {CHART_COLUMNS} FROM published_charts WHERE id = %s;", (chart_id,)
            )
            row = cur.fetchone()
    return _row_to_chart(row) if row else None


def _invalidate_public_cache(token: str) -> None:
    with _public_cache_lock:
        _public_cache.pop(token, None)


