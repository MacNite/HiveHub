def require_publishing() -> None:
    """404 unless publishing is switched on, for public and admin routes alike.

    404 rather than 403 for the same reason the rest of the local dashboard API
    masks itself: on a server that does not run this feature, the routes should
    be indistinguishable from routes that do not exist.
    """
    if not (ENABLE_LOCAL_DASHBOARD and ENABLE_PUBLIC_EMBEDS):
        raise HTTPException(status_code=404, detail="Not Found")


