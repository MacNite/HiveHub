def _embed_base(request: Request) -> str:
    """Origin the embed URLs are built from.

    PUBLIC_BASE_URL when the operator has configured one (the address the outside
    world reaches this server on, which is what belongs in an embed snippet on
    somebody else's website), otherwise the origin this request arrived on.
    """
    if PUBLIC_BASE_URL:
        return PUBLIC_BASE_URL
    return str(request.base_url).rstrip("/")


def _with_urls(chart: dict, base: str) -> dict:
    """Attach the ready-to-paste URLs for one publication."""
    token = chart["token"]
    return {
        **chart,
        "embed_url": f"{base}/embed/chart/{token}",
        "data_url": f"{base}/api/v1/public/charts/{token}",
        "csv_url": f"{base}/api/v1/public/charts/{token}.csv",
    }


@router.get("/api/v1/local/publish/charts", dependencies=PUBLISH_DEP)
def local_list_published_charts(request: Request):
    """Every publication on this server, newest first."""
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.execute(f"SELECT {CHART_COLUMNS} FROM published_charts ORDER BY created_at DESC;")
            rows = cur.fetchall()
    base = _embed_base(request)
    return [_with_urls(_row_to_chart(r), base) for r in rows]


@router.post("/api/v1/local/publish/charts", dependencies=[Depends(require_publishing)])
def local_create_published_chart(
    body: PublishedChartIn, request: Request, admin: dict = Depends(require_dashboard_admin)
):
    """Publish a chart and mint its public token (admin only).

    The publication is live the moment this returns: the embed URL in the
    response serves the data to anyone who has it. Nothing else on the server
    becomes reachable — the token addresses this slice and only this slice.
    """
    spec = _validate_metric(body.metric)
    series = _validate_series(spec, body.series)
    user = get_dashboard_user_by_username(admin["username"])
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.execute(
                f"""
                INSERT INTO published_charts
                    (token, title, subtitle, metric, chart_type, aggregate, series,
                     range_days, options, created_by)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING {CHART_COLUMNS};
                """,
                (
                    _new_token(),
                    body.title.strip(),
                    (body.subtitle or "").strip() or None,
                    body.metric,
                    body.chart_type,
                    body.aggregate,
                    psycopg.types.json.Jsonb(series),
                    body.range_days,
                    psycopg.types.json.Jsonb(body.options.model_dump()),
                    user["id"] if user else None,
                ),
            )
            row = cur.fetchone()
            conn.commit()
    return _with_urls(_row_to_chart(row), _embed_base(request))


@router.patch("/api/v1/local/publish/charts/{chart_id}", dependencies=PUBLISH_ADMIN_DEP)
def local_update_published_chart(chart_id: int, body: PublishedChartUpdateIn, request: Request):
    """Edit a publication in place, keeping its token (admin only).

    Editing rather than re-publishing is the point: an embed already pasted into
    a website keeps working while its title, period or series change under it.
    """
    existing = _fetch_chart_by_id(chart_id)
    if existing is None:
        raise HTTPException(status_code=404, detail="Published chart not found")

    sets: list[str] = []
    params: list[Any] = []
    if body.title is not None:
        sets.append("title = %s")
        params.append(body.title.strip())
    if body.subtitle is not None:
        sets.append("subtitle = %s")
        params.append(body.subtitle.strip() or None)
    if body.chart_type is not None:
        sets.append("chart_type = %s")
        params.append(body.chart_type)
    if body.aggregate is not None:
        sets.append("aggregate = %s")
        params.append(body.aggregate)
    if body.range_days is not None:
        sets.append("range_days = %s")
        params.append(body.range_days)
    if body.options is not None:
        sets.append("options = %s")
        params.append(psycopg.types.json.Jsonb(body.options.model_dump()))
    if body.enabled is not None:
        sets.append("enabled = %s")
        params.append(body.enabled)
    if body.series is not None:
        # The metric cannot change (it decides what the series even mean), so the
        # replacement series are validated against the stored one.
        spec = _validate_metric(existing["metric"])
        sets.append("series = %s")
        params.append(psycopg.types.json.Jsonb(_validate_series(spec, body.series)))
    if not sets:
        return _with_urls(existing, _embed_base(request))

    sets.append("updated_at = now()")
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.execute(
                f"UPDATE published_charts SET {', '.join(sets)} WHERE id = %s "
                f"RETURNING {CHART_COLUMNS};",
                (*params, chart_id),
            )
            row = cur.fetchone()
            conn.commit()
    _invalidate_public_cache(existing["token"])
    return _with_urls(_row_to_chart(row), _embed_base(request))


@router.delete("/api/v1/local/publish/charts/{chart_id}", dependencies=PUBLISH_ADMIN_DEP)
def local_delete_published_chart(chart_id: int):
    """Revoke a publication (admin only). The embed 404s from the next request."""
    existing = _fetch_chart_by_id(chart_id)
    if existing is None:
        raise HTTPException(status_code=404, detail="Published chart not found")
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.execute("DELETE FROM published_charts WHERE id = %s;", (chart_id,))
            conn.commit()
    _invalidate_public_cache(existing["token"])
    return {"status": "deleted", "id": chart_id}


# ── Public API ───────────────────────────────────────────────────────────────


def _load_public_chart(token: str, count_view: bool) -> dict:
    """Fetch an enabled publication by token, optionally counting the view."""
    if not TOKEN_RE.match(token):
        raise HTTPException(status_code=404, detail="Not Found")
    with get_conn() as conn:
        with conn.cursor() as cur:
            if count_view:
                # One statement for the read and the view counter: an embed is
                # fetched once per page view and this keeps that to a single
                # round-trip, while giving the publisher a sign of life.
                cur.execute(
                    f"""
                    UPDATE published_charts
                    SET view_count = view_count + 1, last_viewed_at = now()
                    WHERE token = %s AND enabled
                    RETURNING {CHART_COLUMNS};
                    """,
                    (token,),
                )
                row = cur.fetchone()
                conn.commit()
            else:
                cur.execute(
                    f"SELECT {CHART_COLUMNS} FROM published_charts WHERE token = %s AND enabled;",
                    (token,),
                )
                row = cur.fetchone()
    if row is None:
        raise HTTPException(status_code=404, detail="This chart is not published")
    return _row_to_chart(row)


def _measurements_for(device_ids: list[str], start_at: datetime, max_points: int) -> dict[str, list[dict]]:
    """Chart rows per device over the published period, newest first."""
    out: dict[str, list[dict]] = {}
    with get_conn() as conn:
        with conn.cursor() as cur:
            for device_id in device_ids:
                execute_measurement_query(
                    cur,
                    CHART_MEASUREMENT_COLUMNS,
                    ["device_id = %s", "measured_at >= %s"],
                    [device_id, start_at],
                    max_points,
                    max_points,
                )
                out[device_id] = serialize_chart_measurements(cur)
    return out


def build_public_payload(chart: dict) -> dict:
    """The public representation of a publication: labels, points, nothing else.

    Deliberately free of device ids, hive numbers, firmware versions and every
    other field the private API returns — a published weight curve should not
    also disclose the fleet behind it.
    """
    spec = METRICS.get(chart["metric"])
    if spec is None:
        # A metric removed from the registry after something was published with
        # it. Serve the frame rather than a 500, so the embed degrades visibly.
        raise HTTPException(status_code=410, detail="This chart's metric is no longer available")

    start_at = datetime.now(timezone.utc) - timedelta(days=chart["range_days"])
    aggregate = chart["aggregate"]
    # ~8 samples per day is plenty to pick a daily bucket's extreme, and keeps a
    # short publication from pulling thousands of rows to draw a handful of
    # points. A plain line chart never needs more than the drawn resolution.
    max_points = (
        PUBLIC_MAX_POINTS
        if aggregate == "none"
        else max(PUBLIC_MAX_POINTS, min(AGGREGATE_MAX_POINTS, chart["range_days"] * 8))
    )

    device_ids = list(dict.fromkeys(s["device_id"] for s in chart["series"]))
    per_device = _measurements_for(device_ids, start_at, max_points)

    series_out = []
    newest: Optional[str] = None
    for i, s in enumerate(chart["series"]):
        points = series_points(
            per_device.get(s["device_id"], []),
            metric_keys(chart["metric"], s.get("hive")),
            aggregate,
        )
        latest = points[-1] if points else None
        if latest and (newest is None or latest[0] > newest):
            newest = latest[0]
        series_out.append(
            {
                "label": s["label"],
                "color": PALETTE[i % len(PALETTE)],
                "points": points,
                "latest": None if latest is None else {"at": latest[0], "value": latest[1]},
                # Change across the published period — the number a "how is the
                # colony doing" embed is usually really about.
                "change": None if not points or len(points) < 2 else points[-1][1] - points[0][1],
            }
        )

    options = chart["options"] or {}
    return {
        "title": chart["title"],
        "subtitle": chart["subtitle"],
        "metric": chart["metric"],
        "metric_label": spec["label"],
        "unit": spec["unit"],
        "digits": spec["digits"],
        "chart_type": chart["chart_type"],
        "aggregate": aggregate,
        "range_days": chart["range_days"],
        "theme": options.get("theme", "auto"),
        "height": options.get("height", 320),
        "show_legend": options.get("show_legend", True),
        "show_updated": options.get("show_updated", True),
        "updated_at": newest,
        "generated_at": _iso(datetime.now(timezone.utc)),
        "series": series_out,
    }


def _public_payload_cached(chart: dict) -> dict:
    now = time.monotonic()
    token = chart["token"]
    with _public_cache_lock:
        hit = _public_cache.get(token)
        if hit and now - hit[0] < PUBLIC_CACHE_TTL_SECONDS:
            return hit[1]
    payload = build_public_payload(chart)
    with _public_cache_lock:
        _public_cache[token] = (time.monotonic(), payload)
    return payload


# Public responses are readable from any website's JavaScript (that is the whole
# point of publishing) and may be held briefly by browsers and CDNs. No cookie is
# involved, so the wildcard grants nothing a plain fetch could not already do.
PUBLIC_HEADERS = {
    "Access-Control-Allow-Origin": "*",
    "Cache-Control": "public, max-age=300",
}


@router.get("/api/v1/public/charts/{token}.csv", dependencies=PUBLIC_DEP)
def public_chart_csv(token: str):
    """The published series as CSV, for spreadsheets and static site builds."""
    chart = _load_public_chart(token, count_view=False)
    payload = _public_payload_cached(chart)
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["timestamp", "series", "value", "unit"])
    for s in payload["series"]:
        for at, value in s["points"]:
            writer.writerow([at, s["label"], value, payload["unit"]])
    filename = re.sub(r"[^A-Za-z0-9._-]+", "-", payload["title"]).strip("-").lower() or "chart"
    return PlainTextResponse(
        buf.getvalue(),
        media_type="text/csv; charset=utf-8",
        headers={
            **PUBLIC_HEADERS,
            "Content-Disposition": f'attachment; filename="{filename}.csv"',
        },
    )


@router.get("/api/v1/public/charts/{token}", dependencies=PUBLIC_DEP)
def public_chart_data(token: str):
    """The published slice as JSON: labels, points, units. No device identity."""
    chart = _load_public_chart(token, count_view=True)
    return JSONResponse(_public_payload_cached(chart), headers=PUBLIC_HEADERS)


