@router.get("/embed/chart/{token}", dependencies=PUBLIC_DEP, response_class=HTMLResponse)
def public_chart_page(token: str):
    """A self-contained page rendering one publication, made to be iframed.

    The shell carries no data — only the token — and fetches the JSON above, so
    the page is cheap to cache and the data path is the same one a site owner can
    call directly. Deliberately no X-Frame-Options / frame-ancestors restriction:
    being embedded on someone else's page is the feature.
    """
    chart = _load_public_chart(token, count_view=False)
    html = (EMBED_DIR / "embed.html").read_text(encoding="utf-8")
    # The token matched TOKEN_RE (URL-safe base64) and the title is escaped, so
    # neither can break out of the attribute or the <title> element.
    html = html.replace("{{TOKEN}}", chart["token"]).replace(
        "{{TITLE}}", _escape(chart["title"])
    )
    return HTMLResponse(
        html,
        headers={"Cache-Control": "public, max-age=300", "X-Robots-Tag": "noindex"},
    )


@router.get("/embed/assets/{filename}", dependencies=PUBLIC_DEP)
def public_embed_asset(filename: str):
    """Serve one of the whitelisted embed assets (see EMBED_ASSETS)."""
    path = EMBED_ASSETS.get(filename)
    if path is None or not path.is_file():
        raise HTTPException(status_code=404, detail="Not Found")
    media = "text/javascript" if path.suffix == ".js" else "text/css"
    return FileResponse(
        path,
        media_type=f"{media}; charset=utf-8",
        headers={"Cache-Control": "public, max-age=3600"},
    )


def _escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )
